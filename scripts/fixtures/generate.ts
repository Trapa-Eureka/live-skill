async function buildSampleDocx(): Promise<void> {
  const doc = new Document({
    creator: "live-skill fixtures",
    sections: [
      {
        children: [
          new Paragraph({ text: "New Hire Onboarding Checklist", heading: HeadingLevel.HEADING_1 }),
          new Paragraph({
            children: [
              new TextRun(
                "This fictional checklist is a test fixture only; it describes no real organization or process.",
              ),
            ],
          }),
          new Paragraph({ text: "Before Day One", heading: HeadingLevel.HEADING_2 }),
          new Paragraph({ text: "Provision the laptop and accounts.", bullet: { level: 0 } }),
          new Paragraph({ text: "Ship the welcome kit.", bullet: { level: 0 } }),
          new Paragraph({ text: "First Week", heading: HeadingLevel.HEADING_2 }),
          new Paragraph({ text: "Complete the security training module.", bullet: { level: 0 } }),
          new Paragraph({ text: "Meet with the assigned mentor.", bullet: { level: 0 } }),
          new Paragraph({ text: "Set up the local development environment.", bullet: { level: 0 } }),
        ],
      },
    ],
  });
  writeFileSync(join(DOCS_OUT, "sample.docx"), await Packer.toBuffer(doc));
}

// 예산 초과 테스트용 거대 문서 — 반복되지만 매번 조항 번호가 바뀌는, 완전히 지어낸 문장.
function buildOversizedMd(): void {
  const clause = (i: number): string =>
    `Clause ${String(i)}. The parties acknowledge that this fixture clause exists only to make ` +
    "the document large enough to exceed the compile token budget, and carries no real meaning.";
  const parts: string[] = ["# Oversized Fixture (Fixture)", "", "This document is synthetic and self-authored (guardrail 4)."];
  for (let i = 1; parts.join("\n").replace(/\s+/gu, "").length < 150_000; i++) {
    parts.push("", `## Clause ${String(i)}`, "", clause(i));
  }
  writeFileSync(join(DOCS_OUT, "oversized.md"), parts.join("\n"));
}

async function main(): Promise<void> {
  mkdirSync(DOCS_OUT, { recursive: true });
  mkdirSync(SAMPLES_OUT, { recursive: true });
  await buildRegulationPdf();
  await buildManualPdf();
  await buildSampleDocx();
  buildOversizedMd();
  console.log(`fixtures written to ${DOCS_OUT} and ${SAMPLES_OUT}`);
}

await main();
