// fixtures/docs/*와 samples/manual.pdf의 바이너리(PDF/DOCX) 픽스처를 결정론으로 재생성한다.
// 실행: npm run fixtures — 산출물은 커밋된다, 이 스크립트는 내용을 바꿀 때만 다시 돌리면 된다.
// `npm run check`에는 포함되지 않는다. 전부 이 프로젝트가 직접 지은 가상의 내용이다(가드레일 4).
import { mkdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { Document, HeadingLevel, Packer, Paragraph, TextRun } from "docx";
import PDFDocument from "pdfkit";

const DOCS_OUT = join(process.cwd(), "fixtures", "docs");
const SAMPLES_OUT = join(process.cwd(), "samples");
const FIXED_DATE = new Date("2026-09-06T00:00:00Z");

function pdf(
  outDir: string,
  file: string,
  build: (doc: PDFKit.PDFDocument) => void,
): Promise<void> {
  return new Promise((resolve, reject) => {
    const doc = new PDFDocument({ info: { Title: file, CreationDate: FIXED_DATE, ModDate: FIXED_DATE } });
    const chunks: Buffer[] = [];
    doc.on("data", (c: Buffer) => chunks.push(c));
    doc.on("end", () => {
      writeFileSync(join(outDir, file), Buffer.concat(chunks));
      resolve();
    });
    doc.on("error", reject);
    build(doc);
    doc.end();
  });
}

function heading(doc: PDFKit.PDFDocument, text: string): void {
  doc.font("Helvetica-Bold").fontSize(15).text(text);
  doc.moveDown(0.4);
}

function subheading(doc: PDFKit.PDFDocument, text: string): void {
  doc.font("Helvetica-Bold").fontSize(12).text(text);
  doc.moveDown(0.3);
}

function para(doc: PDFKit.PDFDocument, text: string): void {
  doc.font("Helvetica").fontSize(10).text(text, { align: "left" });
  doc.moveDown(0.8);
}

// 규정풍 조항(가상의 "내부 데이터 보관 정책") — CLAUDE.md 가드레일 4: 자체 제작.
// pdfPagesToText 휴리스틱(core/sections.ts)은 "줄바꿈된 문단의 마지막 줄이 페이지 최장 줄보다 뚜렷이
// 짧다"는 신호로 문단 끝을 찾는다. 문서가 짧으면 한 줄짜리 문단이 우연히 최장 줄의 70%를 넘어 이 신호가
// 흔들릴 수 있어, 모든 문단을 두 줄 이상으로 줄바꿈되게 충분히 길게 쓴다.
const ARTICLES: [string, string][] = [
  [
    "Article 1. Purpose",
    "This fictional policy sets out how the organization retains and disposes of operational data such as log files, support tickets, and configuration backups. It exists only as a test fixture for this project and describes no real organization or process.",
  ],
  [
    "Article 2. Scope",
    "This policy applies to log files, support tickets, and configuration backups generated by internal systems, regardless of which team owns the system. It does not apply to source code repositories or to data held by external processors.",
  ],
  [
    "Article 3. Retention Periods",
    "Log files are retained for ninety days from the date they are written. Support tickets are retained for two years after closure. Configuration backups are retained for one year from the date of the backup.",
  ],
  [
    "Article 4. Disposal",
    "Data past its retention period is deleted within thirty days by an automated job that runs on a nightly schedule. Deletion is logged with the record identifier and the deletion date, but never with the record's content.",
  ],
  [
    "Article 5. Exceptions",
    "Data subject to an active legal hold is retained until the hold is lifted, regardless of the periods set out in Article 3, and the hold itself is recorded together with the name of the requesting team.",
  ],
  [
    "Article 6. Review",
    "This policy is reviewed once every year by the team responsible for data governance. Each review records the reviewer, the review date, and a summary of any period that changed.",
  ],
];

async function buildRegulationPdf(): Promise<void> {
  await pdf(DOCS_OUT, "regulation.pdf", (doc) => {
    heading(doc, "Internal Data Retention Policy (Fixture)");
    para(
      doc,
      "This document is a fictional regulation-style fixture used only for this project's automated tests and describes no real organization, system, or policy.",
    );
    for (const [title, body] of ARTICLES) {
      subheading(doc, title);
      para(doc, body);
    }
  });
}

